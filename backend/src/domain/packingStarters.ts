import type { TemplateItem } from './packing'

/**
 * Templates every household gets (app choice, editable and deletable). Each has a
 * fixed `key`: a household receives each key once (Household.packingStarters), so
 * starters added later reach existing households too, and deleted ones stay gone.
 * Amounts: clothes per day with a cap of 7 (a week, then laundry); no amount
 * where a count doesn't matter.
 */
type Section = TemplateItem['section']
type Amount = Partial<Pick<TemplateItem, 'amount' | 'perDay' | 'maxAmount'>>
const item = (section: Section, text: string, perPerson: boolean, amount: Amount = {}): TemplateItem => ({
   text,
   section,
   perPerson,
   amount: amount.amount ?? null,
   perDay: amount.perDay ?? false,
   maxAmount: amount.maxAmount ?? null,
})
/** For each person. */
const p = (section: Section, text: string, amount?: Amount) => item(section, text, true, amount)
/** Shared. */
const s = (section: Section, text: string, amount?: Amount) => item(section, text, false, amount)
const daily = { amount: 1, perDay: true, maxAmount: 7 }
const fixed = (amount: number) => ({ amount })

export type StarterTemplate = { key: string; name: string; items: readonly TemplateItem[] }

